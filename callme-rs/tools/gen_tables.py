# pyright: basic
"""Generate callme-rs/src/syntax/tables.rs from the running Python interpreter.

The Rust port needs three facts that only CPython knows exactly:

  NON_PRINTABLE         code point ranges for which `str.isprintable()` is False; `ast.unparse`
                        escapes these characters in string literals
  BUILTIN_MODULE_NAMES  `sys.builtin_module_names`: never project modules
  STDLIB_MODULE_NAMES   `sys.stdlib_module_names`: a namespace directory never shadows them

Run it with the Python version the Python implementation is checked against (3.13):

    python3 callme-rs/tools/gen_tables.py > callme-rs/src/syntax/tables.rs
"""
from __future__ import annotations

import sys


def ranges() -> list[tuple[int, int]]:
    """Return the inclusive ranges of non-printable code points, surrogates excluded."""
    out: list[tuple[int, int]] = []
    start = None
    for c in range(0x110000 + 1):
        bad = c <= 0x10FFFF and not (0xD800 <= c <= 0xDFFF) and not chr(c).isprintable()
        if bad and start is None:
            start = c
        elif not bad and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def names(label: str, values: list[str]) -> str:
    """Return a Rust slice constant of the sorted `values`."""
    body = "".join(f'    "{v}",\n' for v in sorted(values))
    return f"pub static {label}: &[&str] = &[\n{body}];\n"


def main() -> None:
    v = sys.version_info
    print(f"//! Tables generated by `tools/gen_tables.py` from Python {v.major}.{v.minor}.{v.micro}; do not edit.")
    print("//!")
    print("//! `NON_PRINTABLE` drives string escaping in `unparse`; the module name lists drive")
    print("//! `frontend::loader`.")
    print()
    print("/// Inclusive code point ranges for which `str.isprintable()` is False (surrogates excluded).")
    print("pub static NON_PRINTABLE: &[(u32, u32)] = &[")
    for a, b in ranges():
        print(f"    (0x{a:X}, 0x{b:X}),")
    print("];")
    print()
    print("/// `sys.builtin_module_names`, sorted.")
    print(names("BUILTIN_MODULE_NAMES", list(sys.builtin_module_names)), end="")
    print()
    print("/// `sys.stdlib_module_names`, sorted.")
    print(names("STDLIB_MODULE_NAMES", list(sys.stdlib_module_names)), end="")


if __name__ == "__main__":
    main()
